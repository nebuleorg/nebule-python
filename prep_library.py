# Header template for the assembled file
HEADER_TEMPLATE = """#!/usr/bin/env python3
# ------------------------------------------------------------------------------------------
# Nebule Python Library - Assembled Version
# 
# This file is automatically generated by prep_library.py from the library/ directory.
# 
# Master Entity: {master_entity}
# Generated: {generated_date}
# 
# WARNING: Any modification of this code will change its footprint and automatically
# result in its invalidation!
# 
# Do not edit this file directly. Edit the source files in library/ instead.
# ------------------------------------------------------------------------------------------

"""

# Footer template
FOOTER_TEMPLATE = """
# ------------------------------------------------------------------------------------------
# End of assembled nebule library
# ------------------------------------------------------------------------------------------
"""


def parse_args():
    """Parse command line arguments."""
    parser = argparse.ArgumentParser(
        description='Assemble nebule Python library into a single file for the o/ directory'
    )
    parser.add_argument(
        '--master-entity',
        type=str,
        required=True,
        help='Entity ID of the master entity'
    )
    parser.add_argument(
        '--master-password',
        type=str,
        required=True,
        help='Private key password for the master entity'
    )
    parser.add_argument(
        '--output',
        type=str,
        default='nebule_library.py',
        help='Output file name in o/ directory (default: nebule_library.py)'
    )
    parser.add_argument(
        '--clean',
        action='store_true',
        help='Clean the o/ directory before assembling'
    )
    parser.add_argument(
        '--verbose',
        action='store_true',
        help='Show verbose output'
    )
    return parser.parse_args()


def log(message, verbose=False):
    """Log a message if verbose is True."""
    if verbose:
        print(message)


def assemble_library(library_dir, output_path, master_entity, master_password, verbose=False):
    """
    Assemble all library files into a single file.
    
    Args:
        library_dir: Path to the library directory
        output_path: Path to the output file
        master_entity: Master entity ID
        master_password: Master entity password
        verbose: Whether to show verbose output
        
    Returns:
        bool: True if successful, False otherwise
    """
    from datetime import datetime
    
    log(f"Assembling library from {library_dir} to {output_path}", verbose)
    
    # Generate header
    generated_date = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    header = HEADER_TEMPLATE.format(
        master_entity=master_entity,
        generated_date=generated_date
    )
    
    # Start assembling
    assembled_content = [header]
    
    # Process each file in order
    for filename in LIBRARY_FILE_ORDER:
        filepath = os.path.join(library_dir, filename)
        
        if not os.path.isfile(filepath):
            log(f"Warning: File not found: {filename}", verbose)
            continue
        
        log(f"  Adding: {filename}", verbose)
        
        # Read file content
        with open(filepath, 'r', encoding='utf-8') as f:
            content = f.read()
        
        # Remove imports from library module to make it self-contained
        # We need to handle multi-line imports (imports with parentheses spanning multiple lines)
        content_lines = content.split('\n')
        filtered_lines = []
        in_library_import = False
        
        for line in content_lines:
            stripped = line.strip()
            
            # Keep empty lines and comments
            if not stripped or stripped.startswith('#'):
                filtered_lines.append(line)
                in_library_import = False
                continue
            
            # Check if we're inside a multi-line import
            if in_library_import:
                # Check if this line ends the import (closing parenthesis)
                if ')' in stripped and not stripped.rstrip().endswith('\\'):
                    in_library_import = False
                # Skip lines inside import
                continue
            
            # Check for library imports
            if stripped.startswith('from library') or stripped.startswith('import library'):
                # This is a library import, skip it
                if '(' in stripped and not ')' in stripped:
                    # Multi-line import
                    in_library_import = True
                continue
            
            # Check for relative imports
            if stripped.startswith('from .') or stripped.startswith('import .'):
                continue
            
            # Keep all other lines (including standard imports)
            filtered_lines.append(line)
        
        content = '\n'.join(filtered_lines)
        
        # Add file marker (optional, can be removed for cleaner output)
        # assembled_content.append(f"\n# ===== {filename} =====\n")
        
        # Add content
        assembled_content.append(content)
        assembled_content.append('\n')
    
    # Add footer
    assembled_content.append(FOOTER_TEMPLATE)
    
    # Write to output file
    try:
        # Create output directory if it doesn't exist
        output_dir = os.path.dirname(output_path)
        if output_dir and not os.path.exists(output_dir):
            os.makedirs(output_dir, exist_ok=True)
        
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write(''.join(assembled_content))
        
        log(f"Successfully assembled library to {output_path}", verbose)
        
        # Make it executable
        os.chmod(output_path, 0o755)
        
        return True
        
    except Exception as e:
        print(f"Error: Failed to write output file: {e}", file=sys.stderr)
        return False


def main():
    """Main entry point."""
    args = parse_args()
    
    # Get paths
    script_dir = os.path.dirname(os.path.abspath(__file__))
    library_dir = os.path.join(script_dir, 'library')
    o_dir = os.path.join(script_dir, 'o')
    output_path = os.path.join(o_dir, args.output)
    
    # Normalize paths to absolute
    library_dir = os.path.abspath(library_dir)
    o_dir = os.path.abspath(o_dir)
    output_path = os.path.abspath(output_path)
    
    # Clean o/ directory if requested
    if args.clean and os.path.exists(o_dir):
        print(f"Cleaning {o_dir}/...")
        for filename in os.listdir(o_dir):
            filepath = os.path.join(o_dir, filename)
            if os.path.isfile(filepath):
                os.remove(filepath)
        print(f"  Removed all files from {o_dir}/")
    
    # Create o/ directory if it doesn't exist
    if not os.path.exists(o_dir):
        os.makedirs(o_dir, exist_ok=True)
        print(f"Created directory: {o_dir}")
    
    # Assemble library
    if not assemble_library(
        library_dir=library_dir,
        output_path=output_path,
        master_entity=args.master_entity,
        master_password=args.master_password,
        verbose=args.verbose
    ):
        sys.exit(1)
    
    print(f"Library assembled successfully: {output_path}")
    print(f"Master entity: {args.master_entity}")
    
    # Verify the output file
    if os.path.isfile(output_path):
        file_size = os.path.getsize(output_path)
        with open(output_path, 'r', encoding='utf-8') as f:
            line_count = sum(1 for _ in f)
        print(f"Output file size: {file_size:,} bytes")
        print(f"Output file lines: {line_count:,}")
    
    return 0


if __name__ == '__main__':
    sys.exit(main())
